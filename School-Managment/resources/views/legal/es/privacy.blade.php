    <h1 class="h-page"><span class="fx-type">Política de privacidad.</span></h1>
    <p class="muted small">Última actualización: 25 de septiembre de 2026</p>

    <p>En ZiberEibar tratamos tus datos personales conforme al Reglamento General de Protección de Datos (Reglamento UE 2016/679, RGPD) y a la Ley Orgánica 3/2018, de Protección de Datos Personales y garantía de los derechos digitales (LOPDGDD).</p>

    <h2>1. Responsable del tratamiento</h2>
    <p>ZiberEibar, con CIF <span class="ph">[CIF]</span> y domicilio en Calle Educación, 1, 20600 Eibar (Gipuzkoa). Contacto: <a href="mailto:info@zibereibar.eus">info@zibereibar.eus</a> · 900 000 000.</p>

    <h2>2. Qué datos tratamos</h2>
    <p>Los datos que nos facilitas o que el centro registra al darte de alta: nombre y apellidos, email, DNI o NIE, teléfono, los cursos en los que te matriculas y tus calificaciones.</p>

    <h2>3. Para qué los usamos</h2>
    <p>Para gestionar tu cuenta de alumno, tus matrículas y la comunicación relacionada con los cursos, como el email de activación de la cuenta. Tus datos se usan únicamente para estos fines.</p>

    <h2>4. Base legal</h2>
    <p>La ejecución de tu matrícula y de la relación formativa con el centro (art. 6.1.b del RGPD) y el cumplimiento de las obligaciones legales que tiene el centro como entidad educativa (art. 6.1.c del RGPD).</p>

    <h2>5. Cuánto tiempo los conservamos</h2>
    <p>Conservamos tus datos mientras tengas relación con el centro y, cuando termine, durante 3 años más para atender posibles responsabilidades. Pasado ese plazo los eliminamos, salvo las que la ley nos obligue a guardar.</p>

    <h2>6. Destinatarios</h2>
    <p>No cedemos tus datos a terceros, salvo cuando una ley nos obligue. Para enviar los emails de la plataforma usamos un proveedor de correo electrónico (Google), que actúa como encargado del tratamiento y solo los utiliza para ese fin.</p>

    <h2>7. Tus derechos</h2>
    <p>Puedes ejercer en cualquier momento tus derechos de acceso, rectificación, supresión, oposición, limitación del tratamiento y portabilidad escribiendo a <a href="mailto:info@zibereibar.eus">info@zibereibar.eus</a> o por correo postal a la dirección del centro. Si consideras que no hemos atendido tu solicitud, puedes presentar una reclamación ante la Agencia Española de Protección de Datos (<a href="https://www.aepd.es" target="_blank" rel="noopener">aepd.es</a>).</p>

    <h2>8. Cookies y almacenamiento local</h2>
    <p>Solo usamos las cookies técnicas necesarias para que la web funcione: la de sesión, para mantenerte conectado, la de protección de formularios y la del idioma que eliges en los ajustes. Tus preferencias de tema y tamaño de texto se guardan en tu propio navegador y no se envían a nuestros servidores. Puedes configurar tu navegador para que te avise o bloquee las cookies, aunque entonces es posible que no puedas iniciar sesión.</p>

